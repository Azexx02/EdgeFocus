// 在指定位置绘制 16x16 大字符（col 为列起始，page 为页起始 0 或 2）
static void _draw_big_char(uint8_t page, uint8_t col, char c)
{
    int idx;
    if (c >= '0' && c <= '9') idx = c - '0';
    else if (c == ':') idx = 10;
    else return;

    for (int i = 0; i < 16; i++) {
        if (col + i < SSD1306_WIDTH)
            _buffer[page * SSD1306_WIDTH + col + i] = font16x16[idx][i];
    }
    for (int i = 0; i < 16; i++) {
        if (col + i < SSD1306_WIDTH)
            _buffer[(page + 1) * SSD1306_WIDTH + col + i] = font16x16[idx][16 + i];
    }
}

void ssd1306_show_countdown_status(uint32_t seconds, const char *status, const char *battery)
{
    char buf[6];
    uint32_t mm = seconds / 60U;
    uint32_t ss = seconds % 60U;

    if (mm > 99U) {
        mm = 99U;
        ss = 59U;
    }

    buf[0] = (char)('0' + (mm / 10U) % 10U);
    buf[1] = (char)('0' + mm % 10U);
    buf[2] = ':';
    buf[3] = (char)('0' + (ss / 10U) % 10U);
    buf[4] = (char)('0' + ss % 10U);
    buf[5] = '\0';

    ssd1306_clear();

    // 5 chars x 16 columns = 80 columns, centered on 128 columns.
    uint8_t col = 24;
    for (int i = 0; i < 5; i++) {
        _draw_big_char(0, col, buf[i]);
        col += 16;
    }

    if (status != NULL) {
        ssd1306_draw_string(2, 0, status);
    }
    if (battery != NULL) {
        ssd1306_draw_string(3, 0, battery);
    }
    ssd1306_update();
}

void ssd1306_show_countdown_seconds(uint32_t seconds)
{
    ssd1306_show_countdown_status(seconds, "Counting", "");
}

void ssd1306_show_countdown(uint16_t minutes)
{
    ssd1306_show_countdown_seconds((uint32_t)minutes * 60U);
}

void ssd1306_show_alert(uint8_t level)
{
    ssd1306_clear();
    ssd1306_draw_string(0, 0, "*** ALERT! ***");

    switch (level) {
        case 1: ssd1306_draw_string(1, 0, "Level 1: Mild");   break;
        case 2: ssd1306_draw_string(1, 0, "Level 2: Phone");  break;
        case 3: ssd1306_draw_string(1, 0, "Level 3: Severe"); break;
        case 4: ssd1306_draw_string(1, 0, "Rest Suggested");  break;
        default: ssd1306_draw_string(1, 0, "Unknown level");   break;
    }

    // 画边框表示警告
    for (int x = 0; x < SSD1306_WIDTH; x++) {
        ssd1306_draw_pixel(x, 0, true);
        ssd1306_draw_pixel(x, SSD1306_HEIGHT - 1, true);
    }
    for (int y = 0; y < SSD1306_HEIGHT; y++) {
        ssd1306_draw_pixel(0, y, true);
        ssd1306_draw_pixel(SSD1306_WIDTH - 1, y, true);
    }

    ssd1306_update();
}
