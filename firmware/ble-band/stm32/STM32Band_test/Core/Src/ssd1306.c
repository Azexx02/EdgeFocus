void ssd1306_show_alert(uint8_t level)
{
    ssd1306_cn_phrase_t phrase;

    ssd1306_clear();
    ssd1306_draw_cn_phrase_center(0, SSD1306_CN_ALERT);

    switch (level) {
        case 1: phrase = SSD1306_CN_GENTLE; break;
        case 2: phrase = SSD1306_CN_PHONE_ALERT; break;
        case 3: phrase = SSD1306_CN_STRONG_ALERT; break;
        case 4: phrase = SSD1306_CN_REST; break;
        default: phrase = SSD1306_CN_UNKNOWN_ALERT; break;
    }
    ssd1306_draw_cn_phrase_center(2, phrase);

    for (int x = 0; x < SSD1306_WIDTH; x++) {
        ssd1306_draw_pixel(x, 0, true);
        ssd1306_draw_pixel(x, SSD1306_HEIGHT - 1, true);
    }
    for (int y = 0; y < SSD1306_HEIGHT; y++) {
        ssd1306_draw_pixel(0, y, true);
        ssd1306_draw_pixel(SSD1306_WIDTH - 1, y, true);
    }

    ssd1306_update();
}
