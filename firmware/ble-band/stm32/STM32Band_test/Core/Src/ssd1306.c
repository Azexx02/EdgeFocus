HAL_StatusTypeDef ssd1306_draw_cn_phrase(uint8_t page, uint8_t col, ssd1306_cn_phrase_t phrase)
{
    if (phrase >= SSD1306_CN_PHRASE_COUNT || page >= 3U) {
        return HAL_ERROR;
    }

    const cn_phrase_seq_t *seq = &cn_phrases[phrase];
    for (uint8_t g = 0U; g < seq->len; g++) {
        if (col >= SSD1306_WIDTH) {
            break;
        }
        const uint8_t *glyph = seq->glyphs[g];
        for (uint8_t i = 0U; i < 16U && (uint8_t)(col + i) < SSD1306_WIDTH; i++) {
            _buffer[page * SSD1306_WIDTH + col + i] = glyph[i];
            _buffer[(page + 1U) * SSD1306_WIDTH + col + i] = glyph[16U + i];
        }
        col = (uint8_t)(col + 16U);
    }
    return HAL_OK;
}

HAL_StatusTypeDef ssd1306_draw_cn_phrase_center(uint8_t page, ssd1306_cn_phrase_t phrase)
{
    if (phrase >= SSD1306_CN_PHRASE_COUNT) {
        return HAL_ERROR;
    }
    uint8_t width = (uint8_t)(cn_phrases[phrase].len * 16U);
    uint8_t col = (width >= SSD1306_WIDTH) ? 0U : (uint8_t)((SSD1306_WIDTH - width) / 2U);
    return ssd1306_draw_cn_phrase(page, col, phrase);
}

static HAL_StatusTypeDef _write_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    return HAL_I2C_Master_Transmit(_hi2c, _addr, buf, 2, 100);
}

static HAL_StatusTypeDef _write_cmds(const uint8_t *cmds, uint16_t len)
{
    uint8_t buf[32];
    buf[0] = 0x00; // control byte: command
    for (uint16_t i = 0; i < len && i < 31; i++) {
        buf[i + 1] = cmds[i];
    }
    return HAL_I2C_Master_Transmit(_hi2c, _addr, buf, len + 1, 100);
}

static HAL_StatusTypeDef _write_data(const uint8_t *data, uint16_t len)
{
    // SSD1306 I2C: control byte 0x40 before data
    // HAL_I2C_Mem_Write handles this well for bulk transfers
    return HAL_I2C_Mem_Write(_hi2c, _addr, 0x40, I2C_MEMADD_SIZE_8BIT,
                             (uint8_t *)data, len, 100);
}

HAL_StatusTypeDef ssd1306_init(const ssd1306_config_t *config)
{
    _hi2c = config->hi2c;
    _addr = config->i2c_addr << 1;  // HAL expects left-shifted address

    // SSD1306 initialization sequence (same as ESP32 version)
    uint8_t init_cmds[] = {
        0xAE,       // Display OFF
        0xD5, 0x80, // Set display clock
        0xA8, 0x1F, // Set multiplex ratio 1/32
        0xD3, 0x00, // Set display offset
        0x40,       // Set start line = 0
        0x8D, 0x14, // Charge pump enable
        0x20, 0x00, // Horizontal addressing mode
        0xA1,       // Segment re-map
        0xC8,       // COM scan direction
        0xDA, 0x02, // COM pins config (for 32-row)
        0x81, 0xCF, // Set contrast
        0xD9, 0xF1, // Pre-charge period
        0xDB, 0x40, // VCOMH deselect level
        0xA4,       // Display from RAM
        0xA6,       // Normal display
        0xAF,       // Display ON
    };

    HAL_StatusTypeDef ret = _write_cmds(init_cmds, sizeof(init_cmds));
    if (ret != HAL_OK) return ret;

    ssd1306_clear();
    ssd1306_update();

    return HAL_OK;
}

HAL_StatusTypeDef ssd1306_clear(void)
{
    memset(_buffer, 0, sizeof(_buffer));
    return HAL_OK;
}

HAL_StatusTypeDef ssd1306_display_on(void)
{
    return _write_cmd(0xAF);
}

HAL_StatusTypeDef ssd1306_display_off(void)
{
    return _write_cmd(0xAE);
}

HAL_StatusTypeDef ssd1306_draw_pixel(uint8_t x, uint8_t y, bool on)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) return HAL_ERROR;

    uint16_t idx = x + (y / 8) * SSD1306_WIDTH;
    if (on)
        _buffer[idx] |= (1 << (y & 7));
    else
        _buffer[idx] &= ~(1 << (y & 7));

    return HAL_OK;
}

HAL_StatusTypeDef ssd1306_draw_string(uint8_t page, uint8_t col, const char *str)
{
    while (*str) {
        char c = *str;
        if (c < 0x20 || c > 0x7E) c = '?';
        uint8_t idx = c - 0x20;

        for (int i = 0; i < 6; i++) {
            _buffer[page * SSD1306_WIDTH + col + i] = font6x8[idx][i];
        }
        col += 6;
        str++;
    }
    return HAL_OK;
}

HAL_StatusTypeDef ssd1306_update(void)
{
    // Set column address range and page address range
    uint8_t addr_cmds[] = {
        0x21, 0x00, 0x7F, // Column address 0-127
        0x22, 0x00, 0x03, // Page address 0-3 (32-row display)
    };
    HAL_StatusTypeDef ret = _write_cmds(addr_cmds, sizeof(addr_cmds));
    if (ret != HAL_OK) return ret;

    // Send entire buffer (512 bytes for 128x32)
    return _write_data(_buffer, sizeof(_buffer));
}

